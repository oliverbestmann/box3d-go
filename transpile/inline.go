package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// ccgo inlines the static inline functions of the headers into their callers, so they do not
// exist as Go functions. inlineSource defines a plain function for each one, which the
// generator then wraps like any other API function.
const inlineSource = "_build/inline.c"

// inlinePrefix is the prefix of the plain functions, followed by the original name.
const inlinePrefix = "b3go_inline_"

var reInline = regexp.MustCompile(`(?m)^B3_(?:FORCE_)?INLINE ([A-Za-z0-9_ ]+?) (b3[A-Za-z0-9_]+)\( ?([^)]*?) ?\)$`)

type inlineFunc struct {
	Result string
	Name   string
	Params []string

	// HasPointer is set for functions with pointer parameters, which are wrapped by hand
	HasPointer bool
}

// readInlineFuncs returns the inline functions of the public headers that return no pointer.
func readInlineFuncs() []inlineFunc {
	headers, err := filepath.Glob("../box3d-c/include/box3d/*.h")
	must(err)

	var funcs []inlineFunc
	for _, header := range headers {
		src, err := os.ReadFile(header)
		must(err)

		for _, match := range reInline.FindAllStringSubmatch(string(src), -1) {
			fn := inlineFunc{Result: match[1], Name: match[2], HasPointer: strings.Contains(match[0], "*")}
			if match[3] != "void" && match[3] != "" {
				fn.Params = strings.Split(match[3], ", ")
			}

			funcs = append(funcs, fn)
		}
	}

	if len(funcs) == 0 {
		panic("no inline functions found")
	}

	return funcs
}

func writeInlineWrappers() {
	var src strings.Builder
	src.WriteString("// Generated by transpile/inline.go, do not edit.\n\n#include \"box3d/box3d.h\"\n#include \"box3d/collision.h\"\n#include \"box3d/math_functions.h\"\n\n")

	for _, fn := range readInlineFuncs() {
		var args []string
		for _, param := range fn.Params {
			fields := strings.Fields(param)
			args = append(args, strings.TrimLeft(fields[len(fields)-1], "*"))
		}

		ret := "return "
		if fn.Result == "void" {
			ret = ""
		}

		fmt.Fprintf(&src, "%s %s%s( %s ) { %s%s( %s ); }\n",
			fn.Result, inlinePrefix, fn.Name, strings.Join(fn.Params, ", "), ret, fn.Name, strings.Join(args, ", "))
	}

	must(os.WriteFile(inlineSource, []byte(src.String()), 0o644))
}
